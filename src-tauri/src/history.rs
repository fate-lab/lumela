//! Screenshot history on disk: `<app data>/history/<id>/{image.png, thumb.png, meta.json, state.json}`.
//! `state.json` is opaque editor state (beautify settings + annotations) owned by the UI.

use std::path::{Path, PathBuf};

use image::RgbaImage;
use serde::{Deserialize, Serialize};

pub const KEEP: usize = 200;
const THUMB: u32 = 360;

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Entry {
    pub id: String,
    /// Unix milliseconds.
    pub created: i64,
    pub source: String,
    pub width: u32,
    pub height: u32,
}

fn valid_id(id: &str) -> Result<(), String> {
    // Ids are generated by us; reject anything that could escape the history dir.
    if !id.is_empty() && id.chars().all(|c| c.is_ascii_alphanumeric() || c == '-') {
        Ok(())
    } else {
        Err("invalid history id".into())
    }
}

fn entry_dir(root: &Path, id: &str) -> Result<PathBuf, String> {
    valid_id(id)?;
    Ok(root.join(id))
}

pub fn new_id(now_ms: i64, seq: u64) -> String {
    format!("{now_ms}-{seq}")
}

pub fn save(root: &Path, entry: &Entry, image: &RgbaImage) -> Result<(), String> {
    let dir = entry_dir(root, &entry.id)?;
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    image.save(dir.join("image.png")).map_err(|e| e.to_string())?;
    let (w, h) = image.dimensions();
    let s = (THUMB as f32 / w.max(h) as f32).min(1.0);
    let thumb = image::imageops::thumbnail(image, ((w as f32 * s) as u32).max(1), ((h as f32 * s) as u32).max(1));
    thumb.save(dir.join("thumb.png")).map_err(|e| e.to_string())?;
    std::fs::write(dir.join("meta.json"), serde_json::to_vec(entry).unwrap()).map_err(|e| e.to_string())
}

/// Newest first.
pub fn list(root: &Path) -> Vec<Entry> {
    let Ok(rd) = std::fs::read_dir(root) else { return vec![] };
    let mut out: Vec<Entry> = rd
        .flatten()
        .filter_map(|d| std::fs::read(d.path().join("meta.json")).ok())
        .filter_map(|b| serde_json::from_slice(&b).ok())
        .collect();
    out.sort_by(|a, b| b.created.cmp(&a.created).then(b.id.cmp(&a.id)));
    out
}

pub fn load(root: &Path, id: &str) -> Result<RgbaImage, String> {
    image::open(entry_dir(root, id)?.join("image.png")).map(|i| i.to_rgba8()).map_err(|e| e.to_string())
}

pub fn thumb(root: &Path, id: &str) -> Result<Vec<u8>, String> {
    std::fs::read(entry_dir(root, id)?.join("thumb.png")).map_err(|e| e.to_string())
}

pub fn get_state(root: &Path, id: &str) -> Result<Option<String>, String> {
    match std::fs::read_to_string(entry_dir(root, id)?.join("state.json")) {
        Ok(s) => Ok(Some(s)),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(e.to_string()),
    }
}

pub fn put_state(root: &Path, id: &str, state: &str) -> Result<(), String> {
    let dir = entry_dir(root, id)?;
    if !dir.exists() {
        return Err("history entry not found".into());
    }
    std::fs::write(dir.join("state.json"), state).map_err(|e| e.to_string())
}

pub fn delete(root: &Path, id: &str) -> Result<(), String> {
    let dir = entry_dir(root, id)?;
    if dir.exists() {
        std::fs::remove_dir_all(dir).map_err(|e| e.to_string())?;
    }
    Ok(())
}

/// Removes the oldest entries beyond `keep`.
pub fn prune(root: &Path, keep: usize) {
    for e in list(root).into_iter().skip(keep) {
        let _ = delete(root, &e.id);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tmp() -> PathBuf {
        let d = std::env::temp_dir().join(format!("scs-history-{}-{}", std::process::id(), rand_suffix()));
        std::fs::create_dir_all(&d).unwrap();
        d
    }
    fn rand_suffix() -> u128 {
        std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap().as_nanos()
    }
    fn entry(id: &str, created: i64) -> Entry {
        Entry { id: id.into(), created, source: "area".into(), width: 4, height: 2 }
    }

    #[test]
    fn round_trip_list_state_delete_prune() {
        let root = tmp();
        let img = RgbaImage::from_pixel(4, 2, image::Rgba([1, 2, 3, 255]));
        save(&root, &entry("1-1", 1), &img).unwrap();
        save(&root, &entry("3-1", 3), &img).unwrap();
        save(&root, &entry("2-1", 2), &img).unwrap();

        assert_eq!(list(&root).iter().map(|e| e.id.as_str()).collect::<Vec<_>>(), ["3-1", "2-1", "1-1"]);
        assert_eq!(load(&root, "2-1").unwrap().get_pixel(0, 0).0, [1, 2, 3, 255]);
        assert!(!thumb(&root, "2-1").unwrap().is_empty());

        assert_eq!(get_state(&root, "2-1").unwrap(), None);
        put_state(&root, "2-1", "{\"a\":1}").unwrap();
        assert_eq!(get_state(&root, "2-1").unwrap().as_deref(), Some("{\"a\":1}"));

        prune(&root, 2);
        assert_eq!(list(&root).len(), 2);
        assert!(load(&root, "1-1").is_err());

        delete(&root, "3-1").unwrap();
        assert_eq!(list(&root).len(), 1);
        std::fs::remove_dir_all(root).ok();
    }

    #[test]
    fn rejects_path_traversal() {
        let root = tmp();
        assert!(load(&root, "../secret").is_err());
        assert!(put_state(&root, "..\\x", "{}").is_err());
        assert!(delete(&root, "").is_err());
        std::fs::remove_dir_all(root).ok();
    }
}
